function X = m_det(A,B)
% Ν άγνωστοι, Μ εξισώσεις
[N,M] = size(A);

% Διακρίνουσα
D = det(A);
A1 = A;
if D~=0 
    for i=1:N
        A(:,i) = B; % Ορίζουσες Δxi
        X(i) = det(A)/D; % Λύση xi
        A = A1;
    end
    disp('Η μοναδική λύση είναι ο πίνακας')
    X % Εμφάνιση λύσης
else
    disp('Το σύστημα είναι αόριστο ή αδύνατο')
end
  