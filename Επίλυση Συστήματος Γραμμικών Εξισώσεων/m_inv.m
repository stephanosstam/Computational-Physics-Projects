function X = m_inv(A,B)
% Ν άγνωστοι(στήλες) , Μ εξισώσεις(γραμμές)
[N,M]=size(A);

% Έλεγχος αν ο πίνακας είναι τετραγωνικός
if (N~=M)
 disp('Ο πίνακας δεν είναι αντιστρέψιμος')
end

% Ορίζουσα
D = det(A);
% Έλεγχος αντιστρεψιμότητας του πίνακα
if D ~= 0
    disp('O A έίναι αντιστρέψιμος.')
    disp('H λύση είναι ο πίνακας')
    Ain = inv(A); % εύρεση αντίστροφου του Α
    X = Ain*B; % λύση
else
    disp('O A δεν είναι αντιστρέψιμος')
end