function A1 = m_Gauss_Cholevsky(A,B)
% Ν άγνωστοι, Μ εξισώσεις
[N,M] = size(A);

% Δημιουργία επαυξημένου πίνακα 
A1 = [A B];

% Γραμμοπράξεις
for j=1:N
    A1(j,:) = A1(j,:)/A1(j,j);
    for i=1:N
        if i~=j
            A1(i,:) = A1(i,:)-A1(i,j)*A1(j,:);
        end
    end
end  

% Εμφάνιση της λύσης
disp('Η λύση του συστήματος είναι ο πίνακας')
A1(:,N+1)